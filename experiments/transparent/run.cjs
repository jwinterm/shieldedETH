"use strict";
const fs = require("node:fs"), path = require("node:path"), assert = require("node:assert/strict");
const { spawnSync } = require("node:child_process"), os = require("node:os");
const { save, sha256 } = require("../../scripts/artifacts"), { calldataCost } = require("./gas.cjs");
const ROOT = path.resolve(__dirname, "../.."), BUILD = path.join(ROOT, "build/transparent");
const REV = "d2fe9cfcc78d8ddbe895042ad0c6310ef2dde7db";
function paperText(e) {
  const best = e.profiles.find(p => p.name === e.selectedProfile), initial = e.profiles.find(p => p.name === "default");
  const fmt = n => n.toLocaleString("en-US");
  return [
    "<!-- Generated by experiments/transparent/run.cjs; do not edit. -->",
    "## Transparent spend feasibility experiment {#sec-transparent-experiment}", "",
    `An isolated one-input, two-output relation retains the depth-32 tree, hidden asset, 128-bit amounts, ownership, commitments and nullifier rules. It compiles to ${fmt(e.circuit.constraints)} constraints. A pinned ProveKit Spartan/WHIR adapter generates and verifies actual native proofs, with Keccak, sumcheck blinding and the zero-knowledge witness-commitment mode. All ${e.circuitTests.length} circuit cases and ${best.negativeChecks.length} native rejection checks per profile pass; both recipient ciphertexts are recovered. This experiment is not integrated into the pool.`, "",
    `The upstream default and twelve witness-commitment tuning profiles retain the upstream 128-bit Johnson-bound commitment target and 10-bit per-slot proof-of-work budget. The default encoded proof occupies ${fmt(initial.transport.bytes)} bytes, including required authentication hints. The smallest measured calldata floor comes from ${e.selectedProfile}: ${fmt(best.transport.bytes)} bytes and ${fmt(e.gas.rawProof.totalGas)} gas in a signed Prague transaction. With public inputs, ABI framing and recipient ciphertexts, the transport charge is ${fmt(e.gas.paymentPayload.totalGas)} gas. These transactions perform no proof verification or payment state changes. Their charges already exceed the provisional 1,000,000-gas ceiling; they are not complete-payment gas measurements. The parameter search is bounded, and these results do not establish a lower bound for other encodings or proof systems.`, "",
    "The tested construction also fails a generic zero-knowledge check. For a two-row relation with identical constraints $x \\cdot 1 = x$, the verifier recovers the unconstrained private witness $x$ from a transmitted alpha evaluation, despite the witness-hiding mode. The counterexample reproduces for every tested profile. It does not establish payment-key extraction. These cost and privacy results reject the tested candidate; A Solidity verifier, insertion integration and a matching Groth16 comparison are not implemented. No qualifying transparent replacement is claimed. Source, dependency pins, test scope and generated evidence are retained under `experiments/transparent/` and `benchmarks/transparent-spend.json`.", ""
  ].join("\n");
}
function run(cmd, args, extra = {}) {
  const r = spawnSync(cmd, args, { cwd: ROOT, encoding: "utf8", maxBuffer: 8 * 1024 * 1024, ...extra });
  if (r.status !== 0 || r.error) throw Error(`${cmd} failed: ${r.error?.message || r.stderr || r.stdout}`);
  return r.stdout.trim();
}
function sourceHashes() {
  const files = ["circuits/lib.circom", "circuits/transfer.circom", "ref/seth8.js", "ref/transactions.js", "package-lock.json", "scripts/artifacts.js"];
  function walk(dir) {
    for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
      if (["node_modules", "target"].includes(e.name)) continue;
      const file = `${dir}/${e.name}`;
      if (e.isDirectory()) walk(file); else files.push(file);
    }
  }
  walk("experiments/transparent");
  return Object.fromEntries(files.sort().map(f => [f, sha256(fs.readFileSync(path.join(ROOT, f)))]));
}
async function main() {
  const dest = path.join(ROOT, "benchmarks/transparent-spend.json");
  if (process.argv.includes("--check")) {
    const evidence = JSON.parse(fs.readFileSync(dest));
    assert.deepEqual(evidence.sourceHashes, sourceHashes(), "transparent experiment evidence is stale");
    assert.equal(evidence.productionEligible, false);
    assert.equal(fs.readFileSync(path.join(ROOT, "docs/_generated/transparent.qmd"), "utf8"), paperText(evidence), "transparent paper excerpt is stale");
    console.log("Transparent experiment evidence matches its source."); return;
  }
  const vendor = path.join(BUILD, "vendor/provekit");
  assert.equal(run("git", ["-C", vendor, "rev-parse", "HEAD"]), REV, "wrong ProveKit revision");
  assert.equal(run("git", ["-C", vendor, "status", "--porcelain"]), "", "modified ProveKit dependency");
  const hashes = sourceHashes();
  console.log(run(process.execPath, ["experiments/transparent/fixture.cjs"]));
  run("cargo", ["+1.98.0", "build", "--release", "--locked", "--offline", "--manifest-path", "experiments/transparent/Cargo.toml"], {
    env: { ...process.env, CARGO_HOME: path.join(BUILD, "cargo-home"), CARGO_TARGET_DIR: path.join(BUILD, "target") }
  });
  const binary = path.join(BUILD, "target/release/seth-transparent-experiment");
  const profiles = [null, ...[1, 2, 3, 4].flatMap(f => [2, 4, 6].map(rate => `${f},${rate}`))];
  const results = [];
  for (const profile of profiles) {
    const name = profile ? `fold${profile.replace(",", "-rate")}` : "default";
    const dir = path.join(BUILD, "profiles", name);
    const env = { ...process.env }; delete env.SETH_WHIR_TUNING;
    if (profile) env.SETH_WHIR_TUNING = profile;
    run(binary, [path.join(BUILD, "spend12.r1cs"), path.join(BUILD, "spend12.wtns"), dir], { env });
    const native = JSON.parse(fs.readFileSync(path.join(dir, "native.json")));
    const proof = Buffer.concat([fs.readFileSync(path.join(dir, "proof.narg.bin")), fs.readFileSync(path.join(dir, "proof.hints.bin"))]);
    const cost = calldataCost(proof);
    results.push({ name, ...native, transport: cost, proofSha256: sha256(proof), schemeSha256: sha256(fs.readFileSync(path.join(dir, "scheme.json"))) });
    console.log(`${name}: ${cost.bytes} bytes; ${cost.floorGas} gas floor; native checks passed.`);
  }
  const best = results.reduce((a, b) => a.transport.floorGas < b.transport.floorGas ? a : b);
  fs.mkdirSync(path.join(BUILD, "proof"), { recursive: true });
  for (const file of ["native.json", "scheme.json", "proof.narg.bin", "proof.hints.bin"])
    fs.copyFileSync(path.join(BUILD, "profiles", best.name, file), path.join(BUILD, "proof", file));
  console.log(run(process.execPath, ["experiments/transparent/gas.cjs"]));
  const gas = JSON.parse(fs.readFileSync(path.join(BUILD, "gas.json")));
  const fixture = JSON.parse(fs.readFileSync(path.join(BUILD, "fixture.json")));
  assert.deepEqual(sourceHashes(), hashes, "experiment sources changed during the run");
  const evidence = { schema: 1, experiment: "transparent-spend12", productionEligible: false,
    generatedAt: new Date().toISOString(), sourceHashes: hashes,
    upstream: { repository: "https://github.com/worldfnd/ProveKit", revision: REV,
      whirRevision: "78e9460420da0954768feb1e52f581a0529c2124" },
    scope: "Native payment-relation proofs, adversarial checks, and Prague calldata-only receipts. No Solidity proof verifier or complete shielded payment.",
    hardware: { cpu: os.cpus()[0].model, arch: os.arch(), node: process.version, rustc: run("rustc", ["+1.98.0", "--version"]) },
    circuit: fixture.constraints, compiler: fixture.compiler, compilerSha256: fixture.compilerSha256,
    circuitTests: fixture.circuitTests, r1csSha256: fixture.r1csSha256,
    recipientRecoveryTested: fixture.recipientRecoveryTested, outgoingRecoveryIncluded: fixture.outgoingRecoveryIncluded,
    profiles: results, selectedProfile: best.name, gas,
    decision: best.transport.floorGas > 1000000 ? "reject tested profiles: proof transport alone exceeds ceiling; generic privacy counterexample also reproduced" : "privacy gate failed; full EVM verification and payment cost unresolved",
    completePaymentGas: null, fullZeroKnowledgeEstablished: false };
  save(dest, evidence);
  fs.writeFileSync(path.join(ROOT, "docs/_generated/transparent.qmd"), paperText(evidence));
  console.log(`Evidence: benchmarks/transparent-spend.json. ${evidence.decision}.`);
}
main().catch(e => { console.error(e.message); process.exitCode = 1; });
